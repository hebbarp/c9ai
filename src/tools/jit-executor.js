// Tool interface for C9AI
async function executeJIT(args) {
  const executor = new JITExecutor();
  const { type, ...params } = args;

  // Cleanup old files on each execution
  executor.cleanupOldFiles();

  try {
    switch (type) {
      case 'calc':
      case 'calculator':
        return await executor.executeCalculator(params.expression);
        
      case 'analyze':
      case 'data':
        return await executor.executeDataAnalyzer(params.file, params.analysis_type);
        
      case 'file':
      case 'process':
        return await executor.executeFileProcessor(
          params.operation, 
          params.input, 
          params.output, 
          params.options
        );
        
      case 'system':
      case 'info':
        return await executor.executeSystemInfo();
        
      case 'quiz':
        return await executor.executeQuizGenerator(
          params.topic || 'frontend',
          params.difficulty || 'intermediate', 
          params.questions || 8
        );
        
      case 'rfq':
      case 'rfq-analysis':
      case 'proposal':
        return await executor.executeRFQAnalysis(
          params.rfq_text || params.text || '',
          params.hourly_rate || 150,
          params.margin_target || 20,
          params.file_path || null
        );
        
      default:
        return {
          success: false,
          error: `Unknown JIT type: ${type}. Supported: calc, analyze, file, system, quiz, rfq`
        };
    }
  } catch (error) {
    return {
      success: false,
      error: `JIT execution failed: ${error.message}`
    };
  }
}

